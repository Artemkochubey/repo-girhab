/** Те же правила в виде Markdown (файл RULES.md). */
export function rulesMarkdown(sections: Section[] = buildRules()): string {
  const out: string[] = [
    '# Правила игры «Семья Легенд»',
    '',
    'Этот файл собирается из кода игры командой `npm run docs:rules`: все числа взяты из констант, поэтому он не расходится с тем, как всё работает. Не правьте его вручную.',
    '',
    '## Оглавление',
    '',
    ...sections.map((s, i) => `${i + 1}. [${s.emoji} ${s.title}](#${s.id})`),
    '',
  ];
  for (const s of sections) {
    out.push(`<a id="${s.id}"></a>`, '', `## ${s.emoji} ${s.title}`, '', `_${s.summary}_`, '');
    for (const b of s.blocks) {
      if (typeof b === 'string') out.push(b, '');
      else if ('list' in b) out.push(...b.list.map((x) => `- ${x}`), '');
      else out.push(`| ${b.table.head.join(' | ')} |`, `|${b.table.head.map(() => '---').join('|')}|`, ...b.table.rows.map((r) => `| ${r.map((c) => c.replace(/\|/g, '\\|')).join(' | ')} |`), '');
    }
  }
  return out.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd() + '\n';
}
